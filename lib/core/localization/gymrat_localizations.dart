class _GymRatLocalizationsDelegate
    extends LocalizationsDelegate<GymRatLocalizations> {
  const _GymRatLocalizationsDelegate();
  @override
  bool isSupported(Locale locale) =>
      ['en', 'sv', 'es', 'ru', 'zh'].contains(locale.languageCode);
  @override
  Future<GymRatLocalizations> load(Locale locale) async =>
      GymRatLocalizations(locale);
  @override
  bool shouldReload(_GymRatLocalizationsDelegate old) => false;
}

extension GymRatText on BuildContext {
  GymRatLocalizations get tr => GymRatLocalizations.of(this);
}
